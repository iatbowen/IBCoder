 ============================================================
 音视频基础与流媒体协议 面试题总结
 ============================================================

 【码率（比特率）】
 单位时间内传输或处理的比特数，单位：kbps（千比特/秒）或 Mbps（兆比特/秒）


 ============================================================
 一、音频基础
 ============================================================

 【声音量化三要素】
 采样大小（Bit Depth）：每个采样点用多少 bit 存储，常用 16 bit。
                       决定动态范围（最大/最小音量的差距），位数越高精度越高。
 采样率（Sample Rate） ：每秒从模拟信号中提取的离散样本数。
                       常用：8k / 16k / 32k / 44.1k / 48kHz
 声道数（Channels）    ：单声道、双声道（立体声）、多声道（5.1 / 7.1）

 音频码率公式：码率 = 采样大小 × 采样率 × 声道数

 【音频感知特性】
 频域遮蔽（Frequency Masking）：强音会遮蔽同时存在的弱音（同一时刻不同频率）
 时域遮蔽（Temporal Masking） ：强音前后短暂时间内的弱音被遮蔽（前掩蔽约 5ms，后掩蔽约 100ms）
 心理声学模型利用这两种效应去除人耳感知不到的信息，实现有损压缩。

 【熵编码】
 哈夫曼编码（Huffman）、算术编码（Arithmetic Coding）、香农编码（Shannon Coding）

 【音频编码格式】
 PCM           ：原始未压缩数据，无编码损失，文件最大
 无损编码       ：FLAC、ALAC（Apple）、WAV、APE
 有损编码       ：MP3、AAC、Opus
   - Opus：低延迟（<50ms）、动态码率（6kbps~510kbps），支持语音/音乐混合，主用 WebRTC / 直播
   - AAC ：MP3 继任者，相同码率下音质更优，主用点播（YouTube、Netflix）
 多声道         ：AC3（杜比）、DTS

 选择建议：
 - 存档/专业     → FLAC 或 WAV
 - 日常听歌      → AAC（256kbps+）或 Opus（160kbps 透明音质）
 - 实时通信      → Opus（自适应码率 + 低延迟）
 - 多声道影视    → AC3（兼容性）或 DTS-HD（高音质）

 【AAC 详解】
 编码规格：
 - LC-AAC（Low Complexity）   ：最基础，复杂度低，中低码率下音质好，适合日常场景
 - HE-AAC                     ：在 LC 基础上加入 SBR（频带复制）技术，低码率表现更好
 - HE-AAC V2                  ：在 HE-AAC 基础上加入 PS（参数立体声），进一步降低带宽

 常用采样率：44.1kHz（CD 标准）、48kHz（专业音频/视频制作）、32kHz（广播）
 常用码率：64kbps（语音）、128/192kbps（一般音乐）、256kbps+（高保真）

 码流格式：
 - ADIF ：只有一个文件头，必须获取全部数据后解码，适合本地文件
 - ADTS ：每帧都有同步头（12bit 0xFFF），可从任意位置开始解码，适合直播流

 文件扩展名：.aac、.m4a、.mp4（容器格式）

 【音频重采样】
 触发原因：
 - 设备采集的采样率/格式与编码器要求不一致
 - 要播放的音频格式与扬声器要求不一致
 工具：FFmpeg libswresample、AudioUnit（iOS）


 ============================================================
 二、视频基础
 ============================================================

 【帧率（FPS）】
 24 fps ：电影标准，呈现电影质感
 30 fps ：网络视频、高清电视（NTSC），YouTube/直播常用
 60 fps ：高帧率游戏视频、运动视频、4K 流媒体
 120 fps：超高帧率，慢动作拍摄、电竞直播
 240 fps：专业慢动作（iPhone/GoPro 慢动作模式）

 【分辨率】
 360p   ：640×360    低清视频、老旧设备
 480p   ：854×480    低带宽直播、移动端
 720p   ：1280×720   主流直播、在线视频（HD）
 1080p  ：1920×1080  高清直播、电影（FHD）
 1440p  ：2560×1440  高端游戏、专业直播（2K/QHD）
 2160p  ：3840×2160  超高清视频、高端直播（4K/UHD）

 【码流计算】
 理论码流（bps）= 宽 × 高 × 帧率 × 色深（12 bit，YUV 4:2:0）× 压缩比
 实际码流（bps）= 文件大小（bit）/ 视频时长（s）

 【YUV（YCbCr）】
 将图像拆分为亮度（Y）和色度（U/V）分量，利用人眼对亮度敏感、对色度不敏感的特点压缩数据。

 组成：
 - Y（Luminance）  ：亮度，描述明暗信息
 - U（Cb）         ：蓝色色差（Blue - Y）
 - V（Cr）         ：红色色差（Red - Y）

 常见采样格式：
 - YUV 4:4:4 ：每像素独立采样色度，无压缩，高质量，用于专业影视后期
 - YUV 4:2:2 ：水平方向 2 像素共享一组色度，色度压缩较小，用于高清电视/广播
 - YUV 4:2:0 ：2×2 像素共享一组色度，数据量为 4:4:4 的 1/2，网络视频/蓝光/H.264 标准

 与 RGB 关系：YUV 用于采集与编码；RGB 用于屏幕展示（渲染前需转换）


 ============================================================
 三、H.264 视频编码
 ============================================================

 【GOP（Group of Pictures）】
 一组连续的帧，由 I 帧、P 帧、B 帧组成：
 - I 帧（Intra Frame）     ：关键帧，仅使用帧内预测编码的完整图像帧，不依赖任何外部参考帧，是 P 帧、B 帧的解码起点，没有 I 帧后续帧无法还原
 - P 帧（Predicted Frame） ：预测帧，基于帧间预测，只存储相对于前方参考帧（I/P 帧）的运动矢量与残差数据
 - B 帧（Bidirectional Frame）：同时参考前向帧（I/P） 与 后向帧（P） 进行双向运动补偿预测，存储双向残差。
 - IDR 帧（Instantaneous Decoding Refresh）：特殊的 I 帧，触发解码器强制清空参考帧缓冲区，从根本上隔断前后帧的依赖关系，错误传播隔断，IDR 之前的解码错误不会蔓延至后续帧
                                           作用：随机访问点（Seek）、直播开始点、网络丢包后快速恢复画面、防止错误传播
 压缩率：   B 帧 > P 帧 > I 帧 = IDR 帧
 解码难度： B 帧 > P 帧 > I 帧 = IDR 帧
 容错能力： IDR 帧 > I 帧 > P 帧 > B 帧
 本质：在压缩效率、解码复杂度、延迟、容错性之间寻求最优平衡

 【H.264 四大压缩技术】
 1. 帧内预测（Intra Prediction）  ：利用同帧相邻像素预测，消除空间冗余（9 种预测方向）
 2. 帧间预测（Inter Prediction）  ：利用前后帧运动矢量预测，消除时间冗余
 3. 变换 + 量化（Transform + Quant）：4×4 整数 DCT 将空域转频域，量化归零小系数，压缩能量
 4. 熵编码（Entropy Coding）       ：CABAC（上下文自适应二进制算术编码），无损进一步压缩

 【宏块（Macroblock，MB）】
 视频帧的基本处理单元，默认 16×16 像素。
 H.264 支持细分：16×16、16×8/8×16（运动区域）、8×8、4×4（细节区域）

 【H.264 码流分层】
 - VCL 层（Video Coding Layer）    ：视频编码核心，结构：Frame → Slice → MB → 子块
 - NAL 层（Network Abstraction Layer）：封装 VCL 数据，处理网络传输的乱序/丢包

 NAL 单元（NALU）结构：
 [NAL Header 1字节] [RBSP Payload]

 码流数据层级：SODB（原始编码比特）→ RBSP（字节对齐）→ NALU（网络传输单元）

 【SPS / PPS / Slice Header】
 - SPS（Sequence Parameter Set）：序列级参数，包含 Profile、Level、分辨率、帧率等
 - PPS（Picture Parameter Set） ：图像级参数，包含量化参数、熵编码类型等
 - Slice Header                  ：帧类型、GOP 中解码帧序号、预测权重、滤波参数

 【Profile 与 Level】
 Profile：规定可使用的编码工具集合
 - Baseline ：不支持 B 帧，低复杂度，用于视频会议/监控
 - Main     ：支持 B 帧和加权预测，用于广播电视/视频存储
 - High     ：支持多参考帧、自适应环路滤波，用于蓝光/4K 流媒体

 Level：限制最大分辨率、帧率、码率的上限
 - Level 3.1：720p/25fps/2Mbps，标清视频
 - Level 4.1：1080p/30fps/10Mbps，高清视频（iOS VideoToolbox 硬解上限）
 - Level 5.1：4K/60fps，超高清视频

 【码流格式】
 Annex B 格式：以起始码（0x000001 / 0x00000001）分隔 NALU，用于文件存储（MP4/TS）
 AVCC 格式   ：以 4 字节长度字段前缀替代起始码，MP4 容器内部使用
 RTP 格式    ：NALU 封装在 RTP 包中，支持分片，用于实时流媒体（WebRTC/SRT）


 ============================================================
 四、H.265（HEVC）与 H.264 对比
 ============================================================

 压缩效率：相同视觉质量下码率降低约 50%（H.265 码率 ≈ H.264 一半）

 核心改进：
 - 编码单元：H.264 最大 16×16 宏块 → H.265 引入 CTU（最大 64×64），更适合 4K/8K
 - 帧内预测：H.264 9 种方向 → H.265 35 种，细节重建更精准
 - 帧间预测：更灵活的参考帧和运动矢量预测
 - 并行处理：Tile/Slice 机制支持多核并行编解码

 代价：
 - 编码复杂度约为 H.264 的 3~10 倍，实时编码需硬件支持
 - 专利费复杂（多个专利池），部分场景仍用 H.264

 选型建议：
 - H.264 ：兼容性优先、实时性要求高（直播推流、视频会议）
 - H.265 ：存储效率优先、高分辨率内容（4K 点播、蓝光、OTT）

 其他编解码器：
 - AV1  ：开源免费，效率接近或优于 H.265，YouTube/Netflix 大量使用，编码复杂度更高
 - VP9  ：Google 开源，YouTube 主力，效率接近 H.265


 ============================================================
 五、PTS / DTS 与音视频同步
 ============================================================

 【PTS（Presentation Time Stamp，显示时间戳）】
 指定该帧应在什么时刻呈现给用户，单位为 time_base（如 1/90000 秒）

 【DTS（Decoding Time Stamp，解码时间戳）】
 指定该帧应在什么时刻送入解码器。
 无 B 帧时 PTS = DTS；含 B 帧时解码顺序与显示顺序不同，DTS ≠ PTS。

 示例（含 B 帧的 GOP）：
 解码顺序（DTS）：I → P → B → P → B → P
 显示顺序（PTS）：I → B → P → B → P → P
 B 帧的 DTS < PTS（需先解码其参考帧，才能完整解码 B 帧）

 【音视频同步（A/V Sync）】
 音视频有独立时钟，网络抖动/丢包导致到达时间不一致，必须对齐保证嘴型匹配。

 同步策略（以音频时钟为基准，最常用）：
 - 视频超前（video PTS > 音频时钟）→ 延迟渲染，等待音频追上
 - 视频落后（video PTS < 音频时钟）→ 丢帧或加速渲染
 - 误差在阈值内（±40ms）         → 直接渲染
 原因：人耳对时序误差比眼睛更敏感，以音频为基准体验更好

 其他策略：
 - 以视频为基准：调整音频播放速率（变速不变调），适合点播
 - 以外部时钟为基准：适合多路流同步场景

 【Jitter Buffer（抖动缓冲）】
 接收端缓存 50~200ms 的包，平滑网络抖动后按序播放，以少量延迟换取稳定体验。


 ============================================================
 六、容器格式（Container Format）
 ============================================================

 容器格式 ≠ 编解码格式。容器负责封装，编解码格式决定压缩方式，两者独立。

 MP4（.mp4 / .m4v）
 - 基于 ISO BMFF，广泛兼容，支持 H.264/H.265/AAC 等
 - moov box 默认在文件末尾，需下载完整文件才能播放
 - faststart 优化：FFmpeg -movflags faststart 将 moov 移到文件头，支持边下边播
 - 适合：点播、本地存储

 FLV（.flv）
 - Adobe 设计，结构：FLV Header + Tag（Video/Audio/Script）
 - 不支持 seek（无索引），适合流式传输
 - 适合：RTMP 直播推流

 TS（Transport Stream，.ts）
 - MPEG-2 规范，固定 188 字节包，容错性强，支持从任意位置解析
 - 每包含 PID 标识音视频流，支持多节目复用
 - 适合：HLS 切片、广播电视

 MKV（.mkv，Matroska）
 - 开放格式，支持几乎所有编解码、多字幕/音轨、章节
 - 适合：本地高质量视频存储

 MOV（.mov）
 - Apple QuickTime 格式，结构与 MP4 相似（同基于 BMFF）
 - iOS/macOS 原生录制格式


 ============================================================
 七、流媒体协议对比
 ============================================================

 【RTMP 与 FLV】
 RTMP ：实时消息传输协议，基于 TCP，负责音视频数据的实时传输（推流端 → 服务器）
 FLV  ：封装格式，用于组织音视频数据；两者常搭配，RTMP 传输 FLV 封装的数据

 【HLS（HTTP Live Streaming）】
 苹果提出的基于 HTTP 的流媒体协议，将音视频切割成 TS 切片，通过 M3U8 播放列表组织。
 - M3U8：文本格式播放列表，描述切片 URL、时长、加密信息等
 - TS  ：实际音视频数据切片（固定 188 字节包，容错性强）
 支持功能：分片播放、HTTPS 加密、自适应码率（ABR）、快/倒放、广告插入
 弊端：延迟高（10~30s），原因：TCP 握手 + M3U8 下载 + TS 切片下载三层延迟

 【RTMP vs HLS vs WebRTC 对比】
 协议       延迟            传输层          适用场景
 RTMP       1~5 秒          TCP             推流、单向直播
 HLS        10~30 秒        HTTP/TCP        点播、高兼容性分发
 WebRTC     <500ms（毫秒级） UDP + RTP/RTCP  视频会议、实时互动

 【WebRTC 特点】
 - 基于 UDP（QUIC）+ RTP/RTCP，支持 P2P 直连，动态码率自适应
 - 内置 AEC（回声消除）、ANS（噪声抑制）、AGC（自动增益控制）
 - 主用：视频会议、实时连麦、1v1 通话

 【直播合流架构（SFU vs MCU）】
 SFU（Selective Forwarding Unit）
   延迟 200~500ms，只转发不处理，主播-连麦者实时交互首选
   例：Agora / 声网 / 腾讯云

 MCU（Multipoint Control Unit）
   延迟 3~10s，服务端混流合成，适合观众侧大规模分发
   例：Zoom / WebEx

 直播连麦最佳实践：SFU（主播/连麦低延迟交互） + MCU/CDN（观众侧合成分发）

 【推流完整链路】
 摄像头/麦克风 → 采集 → 编码（H.264 + AAC）→ FLV 封装 → RTMP 推流 → 流媒体服务器
 播放端：服务器 → RTMP 拉流（FLV）/ HLS 拉流（M3U8+TS）→ 解封装 → 解码 → 渲染


 ============================================================
 八、播放器解码架构
 ============================================================

 【完整播放流水线】
 数据源（网络/本地）
   → 解协议（HTTP/HLS/RTMP/RTP）
   → 解封装 Demuxer（MP4/FLV/TS → 分离音视频 Packet，含 PTS/DTS）
   → 解码 Decoder（视频 → YUV/RGB 帧；音频 → PCM 采样）
   → 音视频同步（以音频时钟为基准）
   → 渲染（视频 → Metal/OpenGL ES；音频 → AudioUnit/AVAudioEngine）

 【软解 vs 硬解】
 软解：CPU 解码（FFmpeg libavcodec），格式兼容性好，功耗高
 硬解：GPU/专用芯片解码，功耗低，延迟低
   iOS：VideoToolbox（VTDecompressionSession），输出 CVPixelBuffer
   Android：MediaCodec

 【iOS 系统 API 分层】
 高层：AVPlayer / AVPlayerLayer，支持 HLS/MP4/本地文件，一行代码播放
 中层：AVSampleBufferDisplayLayer，自定义渲染但系统管理同步
 低层：VideoToolbox + AudioUnit，完全自定义，最低延迟，最高灵活性

 【FFmpeg 各子库职责】
 libavformat    ：解协议 + 解封装（支持 200+ 格式）
 libavcodec     ：软件编解码（支持 100+ 编解码器）
 libavfilter    ：音视频滤镜（缩放、裁剪、水印、调色等）
 libswresample  ：音频重采样（采样率/格式转换）
 libswscale     ：图像格式/尺寸转换（YUV ↔ RGB，缩放）

 iOS 常见组合：FFmpeg 解封装 + VideoToolbox 硬解，兼顾格式兼容性与解码性能。

