/*

 ============================================================
 库、编译与 C 语言特性 面试题总结
 ============================================================

 一、静态库与动态库
 ──────────────────────────────────────────

 【概念】
 库本质上是可执行代码的二进制集合，可被载入内存执行。
 - 静态库（.a / 静态 Framework）：编译时直接复制到可执行文件（Mach-O），运行时不再需要
 - 动态库（动态 Framework / .dylib）：编译时不复制，运行时由 dyld 动态加载并决议符号

 【核心区别】

 文件格式
   · 静态库：.a 文件 + 头文件，或静态 .framework
   · 动态库：.framework（包含动态 Mach-O 二进制）

 链接方式
   · 静态库：编译时直接复制代码到可执行文件
   · 动态库：运行时由 dyld 动态加载，仅绑定符号引用

 应用体积
   · 静态库：增大可执行文件体积
   · 动态库：可执行文件较小，但需附带 .framework 文件

 内存占用
   · 静态库：多 Target 重复加载，内存占用高
   · 动态库：仅加载一次，多进程可共享，内存占用低

 启动时间
   · 静态库：快，代码已在可执行文件中，无需 dyld 加载
   · 动态库：慢，需 dyld 额外加载和符号绑定

 更新维护
   · 静态库：修改后必须重新编译整个应用
   · 动态库：可独立更新（受 iOS 沙盒机制限制）

 符号冲突
   · 静态库：编译时报错（重复符号）
   · 动态库：运行时覆盖（先加载者生效，行为不可控）

 资源管理
   · 静态库：需手动管理图片、xib 等资源
   · 动态库：可直接封装资源到 Framework bundle 内

 【静态库优缺点】
 优点：
 - 启动快：编译时已链接，无 dyld 加载开销
 - 兼容好：支持所有 iOS 版本，无系统限制
 - 独立性强：无外部依赖，代码完全内聚

 缺点：
 - 体积膨胀：多个 Target（主 App + Widget + Extension）各自复制一份，体积叠加
 - 更新成本高：修改后必须重新编译整个应用
 - Dead Code 风险：未启用 -dead_strip 时，未使用代码也会被打包

 【动态库优缺点】
 优点：
 - 体积优化：多 Target 共享一份库文件（系统级动态库如 UIKit 极致共享）
 - 模块化灵活：独立编译，适合大型工程分层
 - 资源内置：可直接封装 Assets.car、xib、字体等资源
 - Swift 友好：Swift 标准库本身是动态库

 缺点：
 - 启动延迟：每个动态库增加 dyld 加载时间，数量过多影响启动速度
 - 沙盒限制：第三方动态库会被复制到 App 包内，无法跨 App 真正共享
 - 符号冲突风险：同名类被先加载者覆盖，行为不可控
 - 系统要求：需 iOS 8+（某些 Swift 动态库要求更高）

 【静态库如何增加包体积】
 1. 编译时完全复制
    静态库在链接时被完整复制到 Mach-O 可执行文件中。
    多个 Target 依赖同一静态库时，每个 Target 都包含一份完整副本：
    例：主 App + Widget 各引用 1MB 静态库 A → 总增加 2MB
    对比：动态库只需一份 .framework（1MB），两者共用

 2. Dead Code Stripping 失效
    静态库未启用 -dead_strip 优化时，所有代码（包括未使用的函数）都会被复制。
    动态库由运行时按需加载，链接时只保留实际引用的符号。


 ============================================================
 二、动态库符号冲突与加载顺序
 ============================================================

 【符号冲突问题】
 两个动态库包含同名但不同实现的类时，Objective-C 运行时不允许同名类共存：
 - 先加载的动态库的类会"覆盖"后加载的同名类，后者被忽略
 - 最终使用哪个版本取决于加载顺序，行为随机，可能导致崩溃
 - iOS 没有命名空间（namespace）机制，类名冲突直接导致符号覆盖

 【加载顺序的决定因素】
 1. Xcode 链接顺序：Build Phases → Link Binary With Libraries 的顺序有影响，但不绝对
 2. 依赖关系：若 LibA 依赖 LibC，LibB 也依赖 LibC，会触发更复杂的加载顺序
 3. dyld 行为：加载顺序由 Mach-O 文件的依赖关系决定，可通过以下命令查看：
    otool -L LibA.framework/LibA

 【解决方案】
 - 为类 / 方法添加唯一前缀（如 ABC_Logger），避免命名冲突
 - Swift 中利用访问控制（internal / private）减少暴露符号
 - 使用模块化隔离（Swift Package / Framework）各自封装命名空间


 ============================================================
 三、Framework 结构与 XCFramework
 ============================================================

 【Framework 的组成结构】
 MyFramework.framework/
 ├── MyFramework          ← 二进制文件（静态或动态，Mach-O 格式）
 ├── Headers/             ← 公开头文件（.h）
 ├── Modules/             ← Swift 模块描述文件（module.modulemap）
 ├── Info.plist           ← 框架元信息
 └── Resources/           ← 资源文件（图片、xib、字体等）

 【XCFramework（Xcode 11+，iOS 推荐格式）】
 传统 Universal Binary（fat binary）将多架构合并在一个文件中，
 但不能同时包含模拟器（x86_64/arm64）和真机（arm64），
 且 App Store 要求提交时去掉模拟器架构，分发流程复杂。

 XCFramework 将不同平台/架构的 Framework 统一打包：
 MyLib.xcframework/
 ├── ios-arm64/                       ← 真机（arm64）
 ├── ios-arm64_x86_64-simulator/      ← 模拟器（arm64 + x86_64）
 └── Info.plist

 优势：
 - 一个文件同时支持真机、模拟器、Mac Catalyst
 - 无需 lipo 手动合并架构
 - Xcode 自动选择正确架构，提交 App Store 无需额外处理
 - 支持 Swift 和 Objective-C 混编


 ============================================================
 四、动态库与 App 启动优化
 ============================================================

 【dyld 加载动态库的流程】
 1. 解析 Mach-O 头，找到 Load Commands 中的依赖动态库列表
 2. 递归加载所有依赖的动态库（系统库已预缓存，第三方库需从磁盘加载）
 3. 符号绑定（Fix-ups）：将代码中对外部符号的引用修正为实际内存地址
 4. ObjC 运行时初始化：注册类、方法、分类等
 5. 执行 +load / __attribute__((constructor)) 初始化代码
 6. 调用 main()

 【启动优化建议】
 - 控制动态库数量：第三方动态库超过 6 个时启动时间明显增加，建议合并或改用静态库
 - 减少 +load 方法：+load 在启动时同步执行，耗时直接影响 pre-main 阶段
 - 使用 DYLD_PRINT_STATISTICS 环境变量分析 pre-main 各阶段耗时
 - 优先使用系统框架：系统动态库已预加载到共享缓存（dyld shared cache），几乎无加载成本


 ============================================================
 五、内联函数（inline）
 ============================================================

 【概念】
 内联函数在编译时将函数体直接嵌入每个调用处，避免函数调用的压栈/出栈开销，
 类似宏替换，但比宏更安全。在代码中用 inline 关键字修饰，
 最终是否内联由编译器根据函数体复杂度和优化级别决定（编译器可忽略 inline 建议）。

 【优缺点】
 优点：
 - 消除函数调用开销（入栈、出栈、跳转）
 - 函数体短时可减小目标代码体积并提升缓存命中率
 - 比宏有类型检查，更安全

 缺点：
 - 函数体较大时会导致目标代码体积膨胀（Code Bloat）
 - 过度内联可能导致指令缓存（I-Cache）命中率下降，反而降低性能
 - 递归函数、含循环的函数通常不适合内联

 【内联函数 vs 宏（#define）】

 处理阶段
   · 宏      ：预处理阶段进行纯文本替换
   · 内联函数：编译阶段语义分析后展开

 类型检查
   · 宏      ：无，参数是纯文本替换，不做类型验证
   · 内联函数：有，参数有类型约束，编译时检查

 调试支持
   · 宏      ：调试时无法进入宏内部，看不到函数名和行号
   · 内联函数：可断点调试，有函数名和行号

 副作用
   · 宏      ：参数可能被多次求值，如 MAX(i++, j++) 会将 i++ 执行两次
   · 内联函数：参数只求值一次，无副作用

 作用域
   · 宏      ：无作用域，#define 后全局生效直到 #undef
   · 内联函数：遵守 C/C++ 作用域和命名空间规则

 使用建议：简短、频繁调用的工具函数（如 min/max、位运算）适合内联；
 复杂函数、递归函数不应使用内联。


 ============================================================
 六、static 关键字
 ============================================================

 【C 程序内存布局】
 1. 正文段（Text）：CPU 机器指令，只读，一个程序只有一份副本
 2. 数据段（Data）：已初始化的全局变量和静态变量
 3. BSS 段         ：未初始化的全局/静态变量，内核自动初始化为 0
 4. 堆（Heap）     ：动态分配内存（malloc/new），向高地址方向增长
 5. 栈（Stack）    ：局部变量、函数返回地址，向低地址方向增长（自顶向下）

 【全局静态变量（static 修饰全局变量）】
 存储位置：静态存储区（数据段 / BSS 段），程序运行期间一直存在
 初始化  ：未初始化时自动置为 0
 作用域  ：仅在声明它的文件内可见（文件作用域），其他文件无法访问
 好处：
 - 防止被其他文件访问或意外修改
 - 不同文件可定义同名全局静态变量，互不冲突

 【局部静态变量（static 修饰局部变量）】
 存储位置：从栈迁移到静态存储区
 生命周期：函数结束后不销毁，程序结束才释放（值在函数调用间持续保留）
 作用域  ：仍为局部作用域，函数外无法访问
 初始化  ：只在首次执行到声明处时初始化一次（线程安全）
           ObjC 的 dispatch_once 与 Swift 的 lazy 底层均基于此机制
 典型应用：单例模式、调用次数统计

 【静态函数（static 修饰函数）】
 函数默认是 extern 的（可被其他文件调用），加 static 后：
 - 仅在声明它的文件中可见，不能被其他文件调用
 - 不同文件可定义同名静态函数，互不冲突
 好处：防止命名污染，实现文件内部的"私有函数"

 【存储说明符对比】
 auto    ：默认局部变量存储类型，进入块时创建，退出块时销毁
 register：建议将变量放入寄存器（现代编译器通常忽略此建议）
 extern  ：声明外部文件的全局变量或函数，不分配内存
 static  ：修饰局部变量时改变生命周期；修饰全局变量/函数时限制作用域

