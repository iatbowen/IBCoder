 ============================================================
 九、常见面试问题
 ============================================================

 Q：OpenClaw 控制平面与执行平面分离的设计有什么好处？
 A：分离后各平面可独立扩展和升级：
    网关层可横向扩容（加机器）应对高并发消息接入，而不影响节点。
    节点可独立升级执行能力（如新增 MCP Server），不影响路由逻辑。
    节点故障只影响该节点的任务，不会导致整个系统崩溃。
    安全边界清晰：网关层做鉴权路由，节点层做权限隔离执行，职责单一。

 Q：节点如何保证执行安全，防止 LLM 生成的指令损坏系统？
 A：多层防御：
    命令白名单：节点只允许执行预定义的 Skill 集合，拒绝白名单外的指令。
    沙箱隔离：不可信代码通过 Docker 容器执行，文件系统和网络访问受限。
    Human-in-the-Loop：删除文件、修改系统配置等危险操作需人工二次确认。
    只读模式：某些工作区可配置为只读，节点只能读取数据不能写入。

 Q：OpenClaw 的 Workspace 隔离机制如何实现多租户或多项目管理？
 A：每个 Workspace 是独立的逻辑空间，拥有独立的：
    LLM 配置（不同项目可用不同模型/系统 Prompt）
    文件访问范围（path prefix 白名单，防止跨项目访问）
    可用工具集（按项目授权 Skills，研发 Workspace 开放 Shell 执行，
    而客服 Workspace 只开放数据库查询）
    历史上下文（对话历史不跨 Workspace 共享）
    实现上类似 Kubernetes 的 Namespace 概念：物理资源共享，逻辑完全隔离。

