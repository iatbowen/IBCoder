 ============================================================
 OpenClaw 架构 面试题总结
 ============================================================

 【核心定位】
 OpenClaw 是一个基于"控制平面（Control Plane）与执行平面（Execution Plane）分离"
 设计的自主 AI Agent 框架，通过分布式"网关-节点"架构，
 实现跨设备、多渠道的 AI 自动化操作。


 ============================================================
 一、整体架构：控制平面与执行平面分离
 ============================================================

 【设计哲学】
 将"决策/路由"与"执行/操作"解耦到两个独立平面：

 控制平面（Control Plane）— 网关层（Gateway）
   负责：消息接入、用户鉴权、任务路由、LLM 调用、状态同步
   部署：建议运行在 24 小时在线的服务器或云主机（高可用）
   特点：无状态路由逻辑，不直接操作任何本地系统

 执行平面（Execution Plane）— 节点层（Node / Agent）
   负责：本地命令执行、文件操作、GUI 感知、结果采集
   部署：安装在需要被操作的终端设备（Mac / Linux / 树莓派）
   特点：有状态，感知宿主系统环境，按网关指令执行具体操作

 【架构优势】
 灵活扩展：网关可连接任意数量的节点，无需重新部署网关
 环境隔离：节点故障不影响网关，网关升级不影响节点
 跨平台：同一网关可同时管理 macOS / Linux / Windows 节点
 轻量化：每个节点只需运行 Agent 进程，不依赖完整 LLM 基础设施


 ============================================================
 二、网关层（Gateway）—— 指挥中枢
 ============================================================

 【核心职责】

 多渠道接入
   对接 Telegram / WhatsApp / Slack / Discord / WebChat 等消息渠道。
   统一消息格式，屏蔽不同渠道的 API 差异，向上游提供统一的消息对象。

 用户鉴权与路由
   识别消息来源用户，匹配其关联的节点（如"张三的 Mac"、"公司服务器"）。
   路由规则支持：按用户、按渠道、按任务类型、按时段分发。

 LLM 调用
   网关作为 LLM 的唯一调用方，将用户指令 + 工具列表 + 上下文组装为 Prompt。
   支持配置不同工作区使用不同 LLM（如研发用 DeepSeek-R1，文案用 Claude）。
   处理 LLM 返回的 Tool Call 指令，转发至对应节点执行。

 状态同步
   维护所有在线节点的心跳状态、配置信息、全局上下文和任务执行历史。
   支持节点断线重连后的任务恢复。

 【默认端口】
 18789：WebSocket 通信端口（网关 ↔ 节点 长连接）
 18790：Web 管理后台（节点管理、路由规则配置、任务监控）


 ============================================================
 三、节点层（Node / Agent）—— 分布式执行单元
 ============================================================

 【核心职责】

 环境感知
   获取宿主系统信息：文件系统目录、进程列表、内存/CPU 状态、网络接口。
   支持 GUI 视觉感知：截图识别（配合视觉模型）、UI 元素定位。

 本地执行
   Shell / Bash 脚本执行（系统命令、文件操作）
   AppleScript / PowerShell（GUI 自动化，如操作 macOS 应用）
   Python / Node.js 代码运行
   MCP 工具调用（通过本地 MCP Server 扩展能力）

 安全隔离
   沙箱执行：通过 Docker 容器或 macOS Sandbox 运行不可信代码，
   防止恶意指令损坏宿主系统（文件删除、网络滥用等）。
   权限控制：节点可配置白名单（允许的命令/目录），拒绝超出范围的操作。

 【节点注册流程】
 1. 节点启动后向网关发起 WebSocket 连接（携带设备 ID 和认证 Token）
 2. 网关验证 Token 并记录节点元信息（设备名、系统类型、在线时间）
 3. 节点定期发送心跳（heartbeat），网关维护节点活跃状态
 4. 网关下发任务时，通过 WebSocket 推送指令 JSON 给对应节点


 ============================================================
 四、技能与工作区（Skills & Workspace）
 ============================================================

 【Skills（技能）】
 基于 MCP 协议或原生 JSON 定义的能力插件，每个 Skill 包含三要素：
   description ：自然语言描述"我能做什么"，供 LLM 判断是否调用
   inputSchema ：JSON Schema，定义参数结构和约束
   handler     ：具体执行逻辑（Shell/Python/API 调用）

 Skill 类型：
   系统类：execute_shell / read_file / write_file / list_directory
   感知类：take_screenshot / get_active_window / get_clipboard
   网络类：http_request / web_search / download_file
   自定义：业务系统 API 封装（如内部 CRM、数据库查询）

 【Workspaces（工作区）】
 逻辑上的任务隔离单元，不同工作区之间数据独立、互不干扰。
 每个工作区可配置：
   关联 LLM：研发工作区用 DeepSeek-R1，文案工作区用 Claude 3.5
   文件权限：仅允许访问特定目录（/workspace/project-a/）
   可用 Skills：按工作区授权不同的工具集
   关联节点：指定任务路由到哪些节点执行

 【Canvas（画布）】
 可视化交互界面，用于展示 AI 生成的代码、Markdown 文档、
 图表（Mermaid/ECharts）或复杂的交互式 UI 组件。
 支持双向交互：用户在 Canvas 上的操作可触发新一轮 Agent 推理。


 ============================================================
 五、通信协议与安全机制
 ============================================================

 【网关 ↔ 节点：WebSocket 长连接】
 采用 JSON-RPC 风格的消息格式：
   请求（网关 → 节点）：{ id, method: "execute", params: { skill, args } }
   响应（节点 → 网关）：{ id, result: { stdout, stderr, exitCode } }
 心跳机制：节点每 30s 发送 ping，超时未响应则标记为离线。
 重连策略：节点断线后指数退避重连（1s → 2s → 4s → 最大 60s）。

 【消息渠道 → 网关：Webhook / Bot API】
 Telegram/Discord：通过官方 Bot API Webhook 推送消息到网关 HTTP 端点。
 消息签名验证：对接收到的 Webhook 消息做 HMAC 签名校验，防止伪造请求。

 【安全威胁与防御】
 Prompt Injection：恶意内容通过工具结果注入 Agent 指令
   → 工具结果标记来源，系统指令与数据内容分区隔离

 权限越界：Agent 执行超出预期范围的系统操作
   → 节点命令白名单 + 沙箱隔离 + 危险操作 Human-in-the-Loop 确认

 Token 泄露：节点认证 Token 被盗用
   → Token 与设备 ID 绑定，支持 Token 轮换和远程吊销


 ============================================================
 六、完整闭环工作流
 ============================================================

 以"帮我查一下 CPU 占用"为例：

 步骤1 输入接收
   用户通过 Telegram 发送消息，Bot API 触发 Webhook 推送到网关 HTTP 端点。

 步骤2 鉴权与路由
   网关验证用户身份，匹配路由规则，确定将任务发送至 Home_Mac 节点。

 步骤3 LLM 推理
   网关调用 LLM（如 DeepSeek-R1），传入：
   用户消息 + 可用 Skills 列表（含 execute_shell 等）+ 对话历史
   LLM 输出 Tool Call：execute_shell({ "command": "top -bn1 | head -20" })

 步骤4 指令下发
   网关通过 WebSocket 将 Tool Call 指令 JSON 推送到 Home_Mac 节点。

 步骤5 本地执行
   节点在沙箱中执行 Shell 命令，采集 stdout 输出，携带 exitCode 返回结果。

 步骤6 结果聚合
   节点 → 网关（原始执行结果）→ LLM（将结果转化为自然语言摘要）→ 网关

 步骤7 回复推送
   网关通过 Telegram Bot API 将 LLM 生成的摘要回复给用户。


 ============================================================
 七、部署架构
 ============================================================

 【轻量化部署（个人/小团队）】
 网关：云服务器（1 核 1G 内存即可，如 VPS/树莓派）
 节点：个人 Mac / Linux 笔记本，运行时无需持续在线
 适用：个人效率工具、家庭自动化、小型团队内部工具

 【企业级部署】
 网关：K8s 集群（多副本高可用）+ 负载均衡
 节点：各业务服务器/开发机，通过内网 VPN 连接网关
 安全：内网隔离 + OAuth 2.0 鉴权 + 操作审计日志
 适用：企业内部 DevOps 自动化、多部门 AI 工具平台


